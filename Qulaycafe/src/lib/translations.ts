export type Language = 'uz' | 'ru' | 'en';

// Menu items now carry their own name/description in all three languages
// (entered by the admin when adding/editing a dish — see nameUz/nameRu/nameEn
// and descriptionUz/descriptionRu/descriptionEn on MenuItem). This replaced
// an old hardcoded translation lookup table keyed by demo item IDs, which
// meant any NEW dish an admin added never translated — only the original
// seeded demo dishes did.
export function getLocalizedMenuItem<
  T extends {
    id: string;
    name: string;
    description: string;
    nameUz?: string;
    nameRu?: string;
    nameEn?: string;
    descriptionUz?: string;
    descriptionRu?: string;
    descriptionEn?: string;
  }
>(item: T, lang: Language): T {
  const nameByLang: Record<Language, string | undefined> = {
    uz: item.nameUz,
    ru: item.nameRu,
    en: item.nameEn
  };
  const descriptionByLang: Record<Language, string | undefined> = {
    uz: item.descriptionUz,
    ru: item.descriptionRu,
    en: item.descriptionEn
  };

  return {
    ...item,
    name: nameByLang[lang] || item.name,
    description: descriptionByLang[lang] || item.description
  };
}

